//             §4-3(445-473), §6-1(1401-1440)
// G0 결정   : G0-23 (docs/g0/G0-RESOLUTION-9.md ④, 219-323), ADR-0004 D1·D2·D3·D4
//
// digest·감사 payload·골든 비교의 **유일한** 직렬화 경로다(§3-1:153).
// `nlohmann::json::dump()` 를 digest 입력에 쓰는 것을 금지한다 — 키 순서와 숫자 표기가
// 구현·플랫폼마다 달라지면 같은 Action 이 다른 `action_digest` 를 내고,
// 승인이 action 에 결합된다는 불변식 5 와 감사 해시체인이 동시에 무너진다.
// 이 헤더가 확정하는 것은 의미가 아니라 **바이트**다. 의미가 같아도 바이트가 다르면 틀린 것이다.
//
// ⚠ 선반영 고지 — 이 파일은 G0-RESOLUTION-9 / ADR-0004 의 **Proposed** 결정을 선반영한
//    초안이며 승인 전에는 규범이 아니다. 승인 전까지 이 헤더를 구현 기준으로 인계하지 않는다.
//    승인 시 이 고지를 제거한다. (docs/STATUS-AUDIT-2026-08-24.md §2-⑥)
#ifndef COGITO_CANONICAL_JSON_HPP
#define COGITO_CANONICAL_JSON_HPP

#include <cstddef>
#include <string>
#include <string_view>

#include <nlohmann/json.hpp>

#include "cogito/result.hpp"

namespace cogito::ccj {

// ─────────────────────────────────────────────────────────────────────────────
// Json — JSON 값 타입
//
// §4-3:455 가 `using Json = nlohmann::json;` 을 규정한다. 자체 값 타입을 새로 만들지
// 않는다 — 코어 의존성이 이미 nlohmann/json 이고(§1 표 17행), 값 타입을 이중화하면
// 변환 지점마다 숫자·키 표현이 갈라져 이 헤더가 막으려는 문제를 되살린다.
//
// 판별·접근은 nlohmann 의 것을 그대로 쓴다.
//   null/bool  : is_null(), is_boolean(), get<bool>()
//   정수/실수  : is_number_integer(), is_number_float(), get<std::int64_t>(), get<double>()
//   문자열/배열/객체 : is_string(), is_array(), is_object()
//
// ★ 이 타입 자체는 아무것도 거부하지 않는다. 중복 키·비UTF-8·깊이·크기 거부는
//   전부 아래 ParseStrict 의 계약이다. 신뢰할 수 없는 입력(LLM·MCP·도구 결과, 불변식 10)이
//   Json 이 되는 경로는 ParseStrict 하나뿐이어야 한다.
//
// ★ 예외 규율 — 코어 예외는 C ABI 경계를 넘지 않는다(G0-09 R3, result.hpp [G0-09 확정 규칙] R3).
//   nlohmann 이 `JSON_NOEXCEPTION` 으로 빌드되면 throw 가 `std::abort()` 로 치환되므로
//   (부록 B-1:3076) 이 헤더의 함수들은 **예외에 의존한 제어흐름을 쓰지 않는다.**
//   실패는 언제나 Result/Error 로 돌려준다.
// ─────────────────────────────────────────────────────────────────────────────
using Json = nlohmann::json;

// ─────────────────────────────────────────────────────────────────────────────
// ParseStrict — 거부하는 파서 (§4-3:460-467)
//
// nlohmann 기본 파서는 중복 키를 조용히 덮어쓴다. 조용한 덮어쓰기는
// "LLM 이 보낸 인자"와 "검증된 인자"를 다르게 만들면서 오류를 내지 않는다 —
// 그래서 기본 파서를 직접 쓰지 않는다.
//
// [거부 사유 — 넷 다 Errc 로 구분해서 돌려준다. 뭉개면 사후 조사가 불가능하다]
//   중복 키          -> Errc::DuplicateKey    (reason::kInputDuplicateKey)
//   비 UTF-8 바이트  -> Errc::NotUtf8         (reason::kInputNotUtf8)
//   깊이 초과        -> Errc::DepthExceeded   (reason::kInputDepthExceeded)
//   크기·키 수 초과  -> Errc::TooLarge        (reason::kInputTooLarge)
// (§4-12 게이트 1단계의 deny 경로가 이 매핑을 그대로 쓴다. 명세서:1475-1479)
// ─────────────────────────────────────────────────────────────────────────────
struct ParseLimits {
  // 아래 세 값은 §4-3:463-465 가 정한 값이다. 임의로 바꾸지 않는다 —
  // 상한을 올리면 게이트 1단계가 통과시키는 입력의 크기가 바뀐다.
  std::size_t max_bytes = 256 * 1024;
  int         max_depth = 32;
  std::size_t max_keys  = 512;

  // 미결 — `max_keys` 가 '객체 하나당' 인지 '문서 전체 누적' 인지를 §3-1·§4-3 어디도
  //        규정하지 않는다. 둘은 거부 경계가 다르다. 제품 책임자 결정 필요.
  //        구현이 임의로 고르지 말고 결정 후 이 주석을 교체한다.
};

// UTF-8 원문 바이트를 받는다. 문자열 리터럴 인코딩을 가정하지 않는다.
// @thread: any — 전역 상태를 읽지도 쓰지도 않는다(§8-4 [T-1] 표기 규약).
//                이 보장은 ADR-0004 D4(로케일 독립)가 지켜질 때만 성립한다.
Result<Json> ParseStrict(std::string_view text, const ParseLimits& lim);

// ─────────────────────────────────────────────────────────────────────────────
// Serialize — CCJ v1 (§3-1:156-169)
//
// **"RFC 8785 준수"라고 쓰지 않는다.** CCJ v1 은 RFC 8785 하위 프로파일이며
// 숫자 규칙이 다르다(부록 A, §1-1:42).
//
// [CCJ-1] 공백 없음. 구분자는 `,` 와 `:` 만.
//
// [CCJ-2] 객체 키는 **UTF-16 code unit 오름차순**으로 정렬한다.
//         ★ 바이트순도 코드포인트순도 아니다. `std::string` 의 기본 `<` 비교(UTF-8 바이트순)로
//           구현하면 BMP 외 문자(surrogate D800~DBFF)가 U+E000~U+FFFF 보다 **뒤로** 가서
//           같은 객체가 다른 바이트열이 된다. 정렬 키 변환을 생략하지 않는다.
//         중복 키는 여기서 처리하지 않는다 — 파싱 단계에서 이미 거부됐다(ParseStrict).
//         따라서 정렬 시 동률 키는 존재하지 않으며 정렬 안정성에 의존할 필요가 없다.
//
// [CCJ-3] 배열 순서 보존. 재정렬 금지.
//
// [CCJ-4] 문자열: `"` `\` 와 U+0000~U+001F 만 이스케이프한다.
//         \b \f \n \r \t 는 짧은 형식, 나머지 제어문자는 **소문자** `\u00xx`.
//         그 외 모든 코드포인트는 UTF-8 원문 그대로 낸다.
//         `\u` 확장 금지. 유니코드 정규화 금지 — 정규화는 입력을 바꾸는 일이고,
//         바뀐 입력의 digest 는 사람이 승인한 그 입력의 digest 가 아니다.
//
// [CCJ-5] 숫자 (ADR-0004 D1 — **골든표가 권위, 서술 규칙이 정정된 쪽이다**)
//         - NaN / Infinity 는 스키마 단계에서 거부되어 여기 도달하지 않는다.
//         - 정수값이고 |v| <= 2^53 이면 십진 정수로 출력한다. -0.0 은 "0".
//         - 그 외에는 C 로케일에서 %.15g -> %.16g -> %.17g 순으로 출력하고,
//           strtod 왕복이 원값과 **비트 동일**한 첫 결과를 채택한다(shortest round-trip).
//         - 지수 표기는 **C99 %g 규칙을 그대로** 따른다: 소문자 'e', 부호 필수,
//           지수는 **최소 두 자리**이며 필요하면 그 이상.
//           **후처리로 선행 0 을 제거하지 않는다.** (G0-RESOLUTION-9 ④:264-270)
//         - %g 는 -4 <= X < P 일 때 %f 스타일을 쓴다. 따라서 2^53 을 넘는 정수도
//           정밀도에 따라 지수형이 아닌 정수 표기가 될 수 있다. **의도된 동작이다.**
//
// [CCJ-5-D3] 정수 fast-path 는 최적화가 아니라 규범이다(ADR-0004 D3).
//         실측상 fast-path 와 순수 %g 는 1e15 에서 갈린다("1000000000000000" vs "1e+15").
//         "어차피 %g 가 같은 값을 낸다"는 이유로 fast-path 를 지우면 digest 가 전부 달라진다.
//
// [CCJ-5-impl] **로케일 독립은 선택이 아니라 계약이다**(ADR-0004 D4, G0-9 ④:285-295).
//         `printf("%g")` 는 로케일 의존적이다. ko_KR/de_DE 에서 소수점이 ',' 가 되면
//         모든 digest 가 달라진다. 전역 로케일은 스레드 간 공유되므로
//         **전역 `setlocale()` 에 의존하는 구현을 금지한다.** 허용 수단은 둘뿐이다.
//           (a) std::to_chars(first, last, v, std::chars_format::general, P)  — 정의상 로케일 독립
//           (b) 로케일을 명시 고정한 snprintf
//               POSIX — newlocale/uselocale 또는 snprintf_l
//               MSVC  — _create_locale(LC_NUMERIC, "C") + _snprintf_s_l
//         ⚠ 미결 — (a)와 (b)가 같은 바이트를 내는지는 **검증되지 않았다.**
//           `to_chars(general)` 의 지수 자릿수 규약이 `%g` 와 동일한지 표준 문언만으로
//           단정할 수 없다. **S1 Exit Gate 의 3-컴파일러 바이트 비교로 판정한다**
//           (ADR-0004:233). 이 헤더는 어느 쪽도 확정하지 않는다.
//
// [CCJ-6] true / false / null 소문자.
//
// 미결 — Serialize 측 깊이·크기 상한이 §3-1 에 없다. ParseLimits 는 **파싱 입력**에만
//        적용되며, 코어가 내부에서 조립한 Json(예: 감사 payload)이 얼마나 깊을 수 있는지는
//        규정이 없다. 임의 상한을 만들지 않는다. 제품 책임자 결정 필요.
// 미결 — 스키마 단계를 우회해 NaN/Infinity 가 담긴 Json 이 Serialize 에 도달했을 때의
//        동작(거부 vs 미정의)을 §3-1 이 규정하지 않는다. fail-closed(불변식 4) 관점에서는
//        거부가 자연스러우나 명세에 없으므로 여기서 확정하지 않는다.
//
// @thread: any — 전역 상태를 읽지도 쓰지도 않는다. [CCJ-5-impl] 이 그 전제다.
// ─────────────────────────────────────────────────────────────────────────────
Result<std::string> Serialize(const Json& j);

// ─────────────────────────────────────────────────────────────────────────────
// SelfTest — [CCJ-7] 기동 시 1회 (§3-1:169, §4-3:469-470)
//
// §3-1-a 골든 벡터 24개를 자가검사한다. **하나라도 불일치하면 프로세스 시작을 실패시킨다.**
// 경고 후 계속 진행하지 않는다 — 직렬화가 1바이트라도 다른 프로세스가 살아서
// 감사 체인에 기록하면, 그 체인은 이후 어떤 도구로도 복구되지 않는다(불변식 4 fail-closed).
//
// 존재 이유는 이론적인 것이 아니다. VS2015 이전 MSVC 는 지수를 세 자리로 냈다(`1e-007`).
// 지원 최소 버전(MSVC 2019 16.11+)은 C99 준수지만, **이 회귀를 잡는 것이 SelfTest 의 존재 이유**다
// (G0-RESOLUTION-9 ④:302-306).
//
// 반환: 성공은 Error::Ok(). 실패는 어느 벡터가 어떻게 어긋났는지 detail 에 담는다.
//       반환값을 무시하면 검사한 의미가 없으므로 [[nodiscard]] 로 강제한다.
//
// ★ 골든 벡터 값을 이 헤더에 하드코딩하지 않는다. 계약과 데이터를 같은 파일에 두면
//   구현이 틀렸을 때 데이터를 고쳐 통과시키게 된다.
// 미결 — §3-1-a:172 는 벡터를 "전부 `tests/canonical/ccj_golden.cpp` 에 상수로 둔다"고
//        규정하는데, SelfTest 는 **런타임 라이브러리**에서 기동 시 돌아야 한다.
//        런타임이 참조할 벡터 상수의 소유 위치(src/ vs tests/ 공유 헤더)가 규정되지 않았다.
//        제품 책임자/Codex 결정 필요.
//
// @thread: 프로세스 기동 스레드에서 정확히 1회. 다른 ccj 함수보다 먼저 호출한다.
//          InitProcessEpoch()(ids.hpp 의 선언) 와의 호출 순서는 명세에 없다 — 미결.
// ─────────────────────────────────────────────────────────────────────────────
[[nodiscard]] Error SelfTest();

// ─────────────────────────────────────────────────────────────────────────────
// 이 헤더가 담당하지 않는 것 — 경계를 여기 적어 둔다
//
//  · LP(length-prefix) 인코딩과 SHA-256, 도메인 태그  -> `digest.hpp` (§2:66, ADR-0004 D5)
//    CCJ 는 LP 의 **입력**을 만들 뿐이다. 두 규격을 한 파일에 섞으면
//    "digest 가 바뀌었다"의 원인이 직렬화인지 인코딩인지 갈라내지 못한다.
//  · 스키마 검증(Tier-G/Tier-V, 키워드 화이트리스트)  -> `tool_schema.hpp` (§3-2)
//    CCJ 는 스키마를 모른다. NaN 거부가 스키마 단계인 것도 그래서다.
// ─────────────────────────────────────────────────────────────────────────────

}  // namespace cogito::ccj

#endif  // COGITO_CANONICAL_JSON_HPP
